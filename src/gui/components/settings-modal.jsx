import { useEffect, useState, useRef, useImperativeHandle } from 'react';
import { Button, Modal, Form, Space, Switch, Tabs, Input, InputNumber, Typography } from 'antd';
import { DeleteOutlined } from "@ant-design/icons";
import { useGlobal } from "@/global-context";
import Table from "@/components/table";
import { dispatchGlobalApiEvent, showNotification, checkForNewVersion, copyToClipboard, base64urlEncode } from "@/utils";
import { FilePathInputFormItem } from "@/components/file-path-input";
import ExternalLink from "@/components//external-link";
import { DEFAULT_MCP_PORT } from "@/../common/constants";

const VariablesEditor = ({ ref }) => {
  const { settings } = useGlobal();
  const [isAddEnabled, setIsAddEnabled] = useState(true);
  const tableRef = useRef();
  const [colDefs, setColDefs] = useState([
    { field: "id", headerName: "Name", width: 170, editable: true },
    { field: "value", headerName: "Value", flex: 1, editable: true },
    {
      field: "actions", headerName: "", width: 40, cellRenderer: (params) => (
        <span className="hover:text-primary" onClick={() => del(params.data.id)}>
          <DeleteOutlined />
        </span>

      )
    }
  ]);

  useEffect(() => {
    if (!settings) {
      return;
    }
    const rows = [];
    if (settings?.global?.variables) {
      for (const name in settings.global.variables) {
        rows.push({ id: name, value: settings.global.variables[name] })
      }
      tableRef.current.addRows(rows);
    }

  }, [settings]);

  useImperativeHandle(ref, () => ({
    get: () => {
      const rows = {};
      for (const row of tableRef.current.getAllRows()) {
        if (row.id in rows) {
          showNotification({
            type: "error",
            message: "Duplicate Variable Name",
            description: `Variable name must be unique, duplicated: ${row.id}`
          })
          return null;
        }
        rows[row.id] = row.value;
      };

      return rows;
    },
  }));

  const add = () => {
    const rowData = tableRef.current.getAllRows();
    if (rowData.find(r => r.id === "")) {
      return;
    }
    tableRef.current.addRows([{ id: "", value: "" }]);
  }

  const del = (id) => {
    tableRef.current.deleteRow(id);
  }

  return (<>
    <div className="h-80">
      <Table
        colDefs={colDefs}
        ref={tableRef}
        onCellEditingStarted={() => setIsAddEnabled(false)}
        onCellEditingStopped={() => setIsAddEnabled(true)}
      />
    </div>
    <div>
      <Button disabled={!isAddEnabled} onClick={add}>Add Variable</Button>
    </div>
    <div className="mt-8">
      Variables are tokens wrapped in {"{{ }}"}. <br />
      They can be used in network requests and are also accessible in scripts through the Utils.getVar(name) function.
      <br />
      To display a variable literally (e.g., {"{{varname}}"}), use the syntax {"{{=varname}}"}.

    </div>
  </>);
}


const GeneralSettings = ({ ref }) => {
  const [form] = Form.useForm();
  const { settings, updateSettings } = useGlobal();

  useEffect(() => {
    if (!settings) {
      return;
    }
    form.setFieldsValue({
      ...(settings?.global?.browser || {})
    });

  }, [settings]);

  useImperativeHandle(ref, () => ({
    get: () => {
      return form.getFieldsValue();
    },
  }));


  const restartBrowser = () => {
    updateSettings("global.browser", form.getFieldsValue());
    dispatchGlobalApiEvent("restartBrowser");
  }

  return (<div>
    <Form form={form} >
      <Form.Item
        name="openDevTools"
        valuePropName="checked"
        label="Open DevTools on browser's windows"
      >
        <Switch size="small" />
      </Form.Item>
      <Form.Item
        name="proxyServer"
        className="flex-none"
        label="Http Proxy Server"
      >
        <Input placeholder="localhost:8080" />
      </Form.Item>
      <FilePathInputFormItem
        name="dataDir"
        className="flex-none"
        label="Persistent data folder"
      />
      <Space>
        <Form.Item
          name="disableCache"
          valuePropName="checked"
          label="Disable browser's cache"
        >
          <Switch size="small" />
        </Form.Item>
        <div className='text-text-secondary-900 italic mb-4 mt--10'>
          It is recommended to disable caching, as some intercepted requests may fail when the cache is enabled.
        </div>
      </Space>
      <Form.Item
        name="disableGPU"
        valuePropName="checked"
        label="Disable GPU"
      >
        <Switch size="small" />
      </Form.Item>
    </Form>
    <div>
      <div className='text-warning mb-4 mt-10'>These settings need a browser restart</div>
      <Button onClick={restartBrowser} >Save and Restart Browser</Button>
    </div>
  </div>

  );
}

// 24 random bytes, base64url (same format as the token generated by the main process)
const generateMcpToken = () => base64urlEncode(crypto.getRandomValues(new Uint8Array(24)));

const McpSettings = ({ form }) => {
  const enabled = Form.useWatch(["mcp", "enabled"], form);
  const port = Form.useWatch(["mcp", "port"], form);
  const token = Form.useWatch(["mcp", "token"], form);
  const url = `http://127.0.0.1:${port || DEFAULT_MCP_PORT}/mcp`;
  const command = `claude mcp add --transport http wirebrowser ${url} --header "Authorization: Bearer ${token}"`;

  const copyCommand = () => {
    copyToClipboard(command, () => {
      showNotification({ type: "success", message: "Command copied to the clipboard" });
    });
  };

  // Generate the token as soon as the server is enabled, so that the
  // command can be copied before saving
  useEffect(() => {
    if (enabled && !token) {
      form.setFieldValue(["mcp", "token"], generateMcpToken());
    }
  }, [enabled, token]);

  return (<div className="mt-10">
    <div className="font-bold mb-2">MCP server (agent access)</div>
    <div className="text-warning mb-4">
      Lets local AI agents (e.g. Claude Code) drive Wirebrowser: they can run JavaScript
      in your pages and read their memory. The server listens on 127.0.0.1 only and requires
      the token below. Keep it disabled when you do not need it.
    </div>
    <Form.Item name={["mcp", "enabled"]} valuePropName="checked" label="Enable MCP server">
      <Switch size="small" />
    </Form.Item>
    <Form.Item name={["mcp", "port"]} label="Port">
      <InputNumber min={1024} max={65535} />
    </Form.Item>
    <div className="flex flex-row items-start gap-3">
      <Form.Item name={["mcp", "token"]} label="Token" className="flex-1">
        <Input.Password readOnly placeholder="Generated when the server is enabled" />
      </Form.Item>
      <Button onClick={() => form.setFieldValue(["mcp", "token"], generateMcpToken())}>
        Regenerate
      </Button>
    </div>
    {enabled && token && (<div>
      <div className="mb-1">Add it to Claude Code:</div>
      <div className="flex flex-row items-start gap-3 mb-2">
        <Typography.Text code className="flex-1 break-all">{command}</Typography.Text>
        <Button size="small" onClick={copyCommand}>Copy</Button>
      </div>
      <div className="italic">Changes to the server (enabling, port, token) apply when the settings are saved.</div>
    </div>)}
  </div>);
};

const AppSettings = ({ ref }) => {
  const [form] = Form.useForm();
  const { appSettings } = useGlobal();
  const [newVersion, setNewVersion] = useState(null);

  useEffect(() => {
    if (!appSettings) {
      return;
    }
    form.setFieldsValue({
      ...(appSettings || {}),
      mcp: {
        enabled: false,
        port: DEFAULT_MCP_PORT,
        token: "",
        ...(appSettings?.mcp || {})
      }
    });

  }, [appSettings]);

  useImperativeHandle(ref, () => ({
    get: () => {
      return form.getFieldsValue();
    },
  }));

  const checkAppUpdates = async () => {
    try {
      const j = await checkForNewVersion();
      setNewVersion(j);
    } catch {
      showNotification({
        type: "error",
        message: "Fetching version information",
        description: `There was an error while fetching version information`
      })
      setNewVersion(null);
    }
  };

  return (<div>
    <Form form={form} >
      <Form.Item
        name="checkForUpdates"
        valuePropName="checked"
        label="Automatically check for updates"
      >
        <Switch size="small" />
      </Form.Item>
      <div className="flex flex-row items-end gap-5">
        <Button onClick={checkAppUpdates} >Check Now</Button>
        {newVersion && (
          newVersion.isNew
            ? (<div>
              New version available {" "}
              <ExternalLink href={`https://github.com/fcavallarin/wirebrowser/releases/tag/v${newVersion.latest}`} text="download" />
            </div>)
            : (
              <div>You already have the latest version</div>
            )
        )}
      </div>
      <McpSettings form={form} />
    </Form>
  </div>

  );
}


const SettingsModal = ({ open, onClose }) => {

  const { updateSettings, updateAppSettings } = useGlobal();
  const varEditorRef = useRef();
  const generalSettigsRef = useRef();
  const appSettigsRef = useRef();
  const [appVersion, setAppVersion] = useState("");

  const tabItems = [
    {
      key: "variables",
      label: "Variables",
      forceRender: true,
      children: <VariablesEditor ref={varEditorRef} />
    },
    {
      key: "general",
      label: "Browser",
      forceRender: true,
      children: <GeneralSettings ref={generalSettigsRef} />
    },
    {
      key: "application",
      label: "Application",
      forceRender: true,
      children: <AppSettings ref={appSettigsRef} />
    },
  ];

  useEffect(() => {
    window.electronAPI.getVersion().then(v => setAppVersion(v));
  }, []);

  const saveSettings = () => {
    const variables = varEditorRef.current.get();
    if (variables === null) {
      return;
    }
    const newSettings = {
      browser: generalSettigsRef.current.get(),
      variables
    };
    updateSettings("global", newSettings);
    updateAppSettings(appSettigsRef.current.get());
    onClose();
  }

  return (
    <Modal
      open={open}
      title="Settings"
      onOk={onClose}
      onCancel={onClose}
      destroyOnHidden={true}
      style={{ top: 20, height: "90vh" }}
      keyboard={false}
      maskClosable={false}
      styles={{
        body: {
          height: "calc(90vh - 110px)",
          overflowY: "auto",
        },
      }}
      width="90vw"
      footer={[
        <Button key="cancel" onClick={onClose}>Cancel</Button>,
        <Button type="primary" key="save" onClick={saveSettings}>Save</Button>,
      ]}
    >
      <Tabs
        items={tabItems}
        animated={false}
      />
      <div className="absolute bottom-0 italic text-[12px] text-bg-container-900">
        Version: {appVersion}
      </div>
    </Modal>
  );
};

export default SettingsModal;